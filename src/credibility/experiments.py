"""Analyses that turn stored dev/holdout predictions into the paper's evidence.

All functions are pure (DataFrames in, DataFrames out) so every table/figure can be regenerated by script.
"""

from __future__ import annotations

import pandas as pd

from credibility.config import EvalConfig
from credibility.evaluation import Task, summarize
from credibility.uncertainty import ConformalConfig, build_intervals, coverage_table


def gate_validation(dev_decisions: pd.DataFrame, hold_summary: pd.DataFrame, alpha: float = 0.05) -> pd.DataFrame:
    """Compare gate decisions made on DEV with what happened on the untouched HOLDOUT.

    outcome: TP (promoted, still beats benchmark on holdout), FP (promoted, does not),
             TN (rejected, does not beat on holdout), FN (rejected, but beats on holdout).
    Also records a 'naive selection' rule (dev skill > 0, no significance test) for comparison.
    """
    d = dev_decisions[["task", "model", "horizon", "skill", "dm_p_adj", "promote", "beats_benchmark", "calibrated"]]
    d = d.rename(columns={"skill": "dev_skill", "dm_p_adj": "dev_p_adj", "promote": "gate_promoted",
                          "beats_benchmark": "dev_beats"})
    h = hold_summary[["model", "horizon", "skill", "dm_p_adj"]].rename(columns={"skill": "hold_skill", "dm_p_adj": "hold_p_adj"})
    m = d.merge(h, on=["model", "horizon"], how="left")
    m["hold_beats"] = (m["hold_skill"] > 0) & (m["hold_p_adj"] < alpha)
    m["naive_selected"] = m["dev_skill"] > 0
    m["outcome"] = [("TP" if p and b else "FP" if p else "FN" if b else "TN")
                    for p, b in zip(m["gate_promoted"], m["hold_beats"])]
    m["naive_outcome"] = [("TP" if p and b else "FP" if p else "FN" if b else "TN")
                          for p, b in zip(m["naive_selected"], m["hold_beats"])]
    return m


def holdout_coverage(dev_preds: pd.DataFrame, hold_preds: pd.DataFrame, task: Task, holdout_start: str,
                     conf: ConformalConfig = ConformalConfig()) -> pd.DataFrame:
    """Out-of-sample interval coverage: calibrate on everything realised before each holdout origin, score holdout rows only."""
    allp = pd.concat([dev_preds, hold_preds], ignore_index=True)
    iv = build_intervals(allp, task, conf)
    iv = iv[iv["origin_date"] >= pd.Timestamp(holdout_start)]
    return coverage_table(iv, task, alpha=conf.alpha)


def dev_and_holdout_tables(cfg: EvalConfig, task: Task, dev_preds: pd.DataFrame, hold_preds: pd.DataFrame):
    """(dev summary, holdout summary) with identical statistics."""
    return summarize(dev_preds, cfg, task), summarize(hold_preds, cfg, task)


def confusion(val: pd.DataFrame, col: str = "outcome") -> dict[str, int]:
    return {k: int((val[col] == k).sum()) for k in ("TP", "FP", "TN", "FN")}
